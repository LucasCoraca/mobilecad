"""Python-implemented FreeCAD commands -> the module that registers them (FreeCADGui.addCommand), relative to the
workbench folder.  Writes engine/python/mobilecad/command_modules.py.  Usage: python3 -I gen_command_modules.py <research> <out>"""
import json, os, sys
research, out = sys.argv[1], sys.argv[2]
cmds = json.load(open(os.path.join(research, 'freecad_commands.json')))['commands']
m = {}
for name, c in sorted(cmds.items()):
    f = c.get('file', '')
    if not f.endswith('.py') or not f.startswith('src/Mod/'): continue
    wb, rel = f[len('src/Mod/'):].split('/', 1)
    m[name] = (wb, rel)
# commands registered indirectly (CAM's SetupOperation/SetupCommand, group commands in InitGui ...): the Python file
# that mentions the quoted command name, preferring the implementation over InitGui
root = os.path.expanduser('~/Android/freecad-src/src/Mod')
allnames = json.load(open(os.path.join(research, 'FREECAD_COMMANDS.json')))
allnames = [n for wb in allnames.values() for n in (wb if isinstance(wb, list) else wb.keys())] if isinstance(allnames, dict) else []
texts = {}
for dp, _, fs in os.walk(root):
    for f in fs:
        if f.endswith('.py') and 'test' not in dp.lower(): texts[os.path.join(dp, f)] = open(os.path.join(dp, f), errors='ignore').read()
for name in allnames:
    if name in m or not isinstance(name, str) or not name.split('_')[0] in ('CAM', 'BIM', 'Arch', 'FEM', 'OpenSCAD', 'IFC', 'Assembly', 'MeshPart', 'TemplatePyMod', 'PartDesign', 'Draft'): continue
    hits = [p for p, t in texts.items() if ('"%s"' % name) in t or ("'%s'" % name) in t]
    if not hits: continue
    hits.sort(key=lambda p: (p.endswith('InitGui.py'), len(p)))
    rel = os.path.relpath(hits[0], root); wb, r = rel.split('/', 1)
    m[name] = (wb, r)
# CAM operations register as 'CAM_' + the name given to PathOpGui.SetupOperation("Name", ...) in their own file
import re
for p, t in texts.items():
    for name in re.findall(r'SetupOperation\(\s*"([\w ]+)"', t):
        rel = os.path.relpath(p, root); wb, r = rel.split('/', 1)
        if wb == 'CAM': m.setdefault('CAM_' + name.replace(' ', '_'), (wb, r))
with open(out, 'w') as o:
    o.write('"""Generated by research/gen_command_modules.py: FreeCAD Python command -> (workbench folder, source file)."""\n')
    o.write('MODULES = {\n')
    for k, (wb, rel) in m.items(): o.write('    %r: (%r, %r),\n' % (k, wb, rel))
    o.write('}\n')
print(len(m), 'python commands')
