"""MobileCAD mark: an isometric cube with its near corner chamfered (a CAD operation), in FreeCAD's red/blue family.
Writes branding/mobilecad.svg (master), the app's vector drawables, and PNGs for stores / the download page."""
import math, os, sys
R = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(R, '..', 'app', 'app', 'src', 'main', 'res')
BLUE, RED, RED_D, FACET = '#418FDE', '#E0403F', '#A8262E', '#DDE7F3'
def geom(cx, cy, s, t=0.30):
    """Hexagon of an isometric cube of 'radius' s around (cx, cy); faces with the near corner chamfered at t."""
    h = s * math.sqrt(3) / 2
    top, ur, lr, bot, ll, ul, c = (cx, cy - s), (cx + h, cy - s / 2), (cx + h, cy + s / 2), (cx, cy + s), (cx - h, cy + s / 2), (cx - h, cy - s / 2), (cx, cy)
    L = lambda p, q: (p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t)
    a, b, d = L(c, ul), L(c, ur), L(c, bot)
    return [(BLUE, [top, ur, b, a, ul]), (RED, [ul, a, d, bot, ll]), (RED_D, [b, ur, lr, bot, d]), (FACET, [a, b, d])]
def path(pts): return 'M' + ' L'.join('%.2f,%.2f' % p for p in pts) + ' Z'
def svg(size=512, bg=None, s=None):
    s = s or size * 0.40; body = ''.join('<path fill="%s" d="%s"/>' % (c, path(p)) for c, p in geom(size / 2, size / 2, s))
    back = '<rect width="%d" height="%d" rx="%d" fill="%s"/>' % (size, size, size * 0.22, bg) if bg else ''
    return '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">%s%s</svg>' % (size, size, size, size, back, body)
def vector(vp, s, mono=False):
    ps = ''.join('\n    <path android:fillColor="%s" android:pathData="%s"/>' % ('#FFFFFFFF' if mono else c, path(p))
                 for c, p in geom(vp / 2, vp / 2, s) if not (mono and c == FACET))
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by branding/make_logo.py -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="%ddp" android:height="%ddp" android:viewportWidth="%d" android:viewportHeight="%d">%s\n</vector>\n') % (vp, vp, vp, vp, ps)
open(os.path.join(R, 'mobilecad.svg'), 'w').write(svg())
open(os.path.join(R, 'mobilecad-icon.svg'), 'w').write(svg(512, '#FFFFFF', 512 * 0.33))
dr = os.path.join(RES, 'drawable'); os.makedirs(dr, exist_ok=True)
open(os.path.join(dr, 'ic_launcher_foreground.xml'), 'w').write(vector(108, 30))       # inside the 66dp safe zone
open(os.path.join(dr, 'ic_launcher_monochrome.xml'), 'w').write(vector(108, 30, mono=True))
open(os.path.join(dr, 'app_logo.xml'), 'w').write(vector(48, 22))
if '--png' in sys.argv:
    import cairosvg
    for name, src, px in (('mobilecad-512.png', svg(512, '#FFFFFF', 512 * 0.33), 512), ('mobilecad-mark-512.png', svg(), 512), ('favicon-64.png', svg(64, '#FFFFFF', 64 * 0.36), 64)):
        cairosvg.svg2png(bytestring=src.encode(), write_to=os.path.join(R, name), output_width=px, output_height=px)
