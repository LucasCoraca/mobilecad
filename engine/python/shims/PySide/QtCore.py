class QIODevice:
    ReadOnly = 1
    WriteOnly = 2
    Text = 16


class QByteArray(bytes):
    def data(self):
        return bytes(self)


class QFile:
    """QFile over the files packaged in bridge/qtres (resource paths) or the real file system."""
    Text = QIODevice.Text

    def __init__(self, name):
        self._path = _os.path.join(_QTRES, name[2:]) if name.startswith(':/') else name
        self._fh = None

    def open(self, mode):
        try:
            self._fh = open(self._path, 'rb' if mode & QIODevice.ReadOnly else 'wb')
            return True
        except OSError:
            return False

    def readAll(self):
        return QByteArray(self._fh.read())

    def close(self):
        if self._fh: self._fh.close(); self._fh = None

    def exists(self):
        return _os.path.exists(self._path)


